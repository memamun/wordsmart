/// Centralized spacing tokens for the WordSmart design system.
///
/// Use these constants instead of inline numeric padding/margin
/// values to maintain a consistent spatial rhythm across the app.
abstract final class AppSpacing {
  /// 4.0 — tight internal padding
  static const double xs = 4;

  /// 8.0 — small gaps, icon padding
  static const double sm = 8;

  /// 12.0 — medium internal spacing
  static const double md = 12;

  /// 16.0 — standard content padding
  static const double lg = 16;

  /// 20.0 — section gaps
  static const double xl = 20;

  /// 24.0 — large section padding
  static const double xxl = 24;

  /// 32.0 — page-level top/bottom margins
  static const double xxxl = 32;

  /// 48.0 — hero spacing
  static const double hero = 48;

  // ── Border Radius ─────────────────────────────────────────────
  /// 8.0 — small rounded corners (chips, tags)
  static const double radiusSm = 8;

  /// 12.0 — standard rounded corners (cards, tiles)
  static const double radiusMd = 12;

  /// 16.0 — large rounded corners (modals, sheets)
  static const double radiusLg = 16;

  /// 24.0 — pill shapes (buttons, badges)
  static const double radiusXl = 24;
}
